    private void btnAssignRoomActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAssignRoomActionPerformed
        
   String numberText = cmbRoomNumber.getSelectedItem().toString().trim();
    String guestName = txtGuestName.getText().trim();

    if (numberText.isEmpty() || guestName.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Please enter the room number and guest name.");
        return;
    }

    int roomNumber;

    try {
        roomNumber = Integer.parseInt(numberText);
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Please enter a valid room number.");
        return;
    }

    if (manager.assignRoom(roomNumber, guestName)) {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Room successfully assigned!");
        
           jButton1ActionPerformed(null);
    } else {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Room not found or already occupied!");

    }

    }//GEN-LAST:event_btnAssignRoomActionPerformed

    private void btnVacateRoomActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVacateRoomActionPerformed
           // Get the room number
   String numberText = cmbRoomNumber.getSelectedItem().toString().trim();
    // Check if the field is empty
    if (numberText.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Please enter the room number.");
        return;
    }

    int roomNumber;

    // Convert text into an integer
    try {
        roomNumber = Integer.parseInt(numberText);
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Please enter a valid room number.");
        return;
    }

    // Vacate the room
    if (manager.vacateRoom(roomNumber)) {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Room successfully vacated!");

     cmbRoomNumber.setSelectedIndex(0);
        txtGuestName.setText("");
       jButton1ActionPerformed(null);
    } else {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Room not found or is not occupied!");

    }
    }//GEN-LAST:event_btnVacateRoomActionPerformed

    private void btnAddRoomActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddRoomActionPerformed
         // Get the room number
 

    // Get selected room number
    String numberText = cmbRoomNumber.getSelectedItem().toString().trim();

    int roomNumber;

    try {
        roomNumber = Integer.parseInt(numberText);
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Please select a valid room number.");
        return;
    }

    // Get selected room type
    String roomType = cmbRoomType.getSelectedItem().toString();

    Room newRoom;

    if (roomType.equals("Standard")) {
        newRoom = new StandardRoom(roomNumber, "Standard Bed");
    } else {
        newRoom = new DeluxeRoom(roomNumber, "Premium Feature");
    }

    // Add room
    if (manager.addRoom(newRoom)) {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Room successfully added!");

        // AUTOMATICALLY DISPLAY THE ROOM IN THE TABLE
        jButton1ActionPerformed(null);

        // Reset fields
        cmbRoomNumber.setSelectedIndex(0);
        txtGuestName.setText("");

    } else {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Room number already exists or room array is full!");
    }

    
    }//GEN-LAST:event_btnAddRoomActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       
    // Get the table model
    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tblRooms.getModel();

    // Clear the old table records
    model.setRowCount(0);

    // Get all rooms from the array
    for (int i = 0; i < manager.getRoomCount(); i++) {

        Room room = manager.getRoomAt(i);

        String roomType;

        if (room instanceof StandardRoom) {
            roomType = "Standard";
        } else {
            roomType = "Deluxe";
        }

        // Add room information to the table
        model.addRow(new Object[]{
            room.getRoomNumber(),
            room.getGuestName(),
            roomType,
            room.getStatus()
        });
    }

    }//GEN-LAST:event_jButton1ActionPerformed

